from __future__ import annotations

#: 「増やす」と読める動詞。★ 「入れて」は 1 セルの言い方にも出るので、向きの語と**対**で見る。
PLACING_VERBS = ("足し", "足す", "追加", "挿入", "入れ", "作っ", "作る", "増やし", "増やす")


def task_places_a_new_row(task: str, after_words, before_words, between=None) -> bool:
    """依頼が「〜の下/上/間に … 足す」と言っているか。

    after_words / before_words: 行の位置の語（ailine.py の _ANCHOR_AFTER/_BEFORE）。
    between: 「A と B の間」を拾う正規表現（無ければ見ない）。
    ★ 語彙は呼び出し側から渡す ── 同じ語を 2 箇所に持たない。
    """
    t = task or ""
    if not any(v in t for v in PLACING_VERBS):
        return False
    if any(w in t for w in tuple(after_words) + tuple(before_words)):
        return True
    return bool(between and between.search(t))
