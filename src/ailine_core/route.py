"""断る前に「それは**別のコマンドで出来る**」と言えるか。

★★ なぜ在るか（2026-09-08・盲検の検品が挙げた摩擦）:

    依頼   「この表を **PDF** にして」
    出力   `？ この依頼（PDF出力）は、頼める操作の一覧に照合できませんでした。
            要望として記録します。`

  ★ この道具は `ailine export-pdf` を**持っている**。断り自体は正しい（`run` の
    操作一覧には無い）が、「要望として記録します」は**持っていない物言い**で、
    初めての人はそこで諦める。★ 在るのに案内しない ── 実装の欠けではなく導線の欠け。

★ 出すのは断りの中だけ ── 既にできないと決まった後なので、外しても害は小さい。
  それでも語は**紛れの無いものだけ**にする（「まとめて」等は表の中の操作と衝突する）。

★ 番人（tests/test_a_refusal_points_at_the_command_that_can.py）が、ここに書いた
  コマンド名が**実在すること**を機械で確かめる ── 存在しない道具へ人を送らない。
★ ailine を import しない（可搬性の番人が機械で守る層）。
"""
from __future__ import annotations

#: (依頼文に現れる語, コマンド, 一行の説明)。★ 上から順に見て最初に当たったものを返す。
ROUTES = (
    (("PDF", "ＰＤＦ", "pdf"), "ailine export-pdf",
     "表を PDF にして、出した PDF を読み戻して確かめます"),
    (("CSV", "ＣＳＶ", "csv"), "ailine export-csv",
     "シートを CSV に書き出します（0 落ちを作りません）"),
    (("元に戻", "取り消し", "取り消して", "やり直"), "ailine undo",
     "原本へ反映する前のバックアップから戻します"),
)


def command_that_can_do_this(task: str) -> tuple | None:
    """依頼文が、`run` では出来ないが**別のコマンドなら出来る**ことを指していれば
       `(コマンド, 一行の説明)` を返す。当たらなければ None。"""
    for words, cmd, note in ROUTES:
        if any(w in (task or "") for w in words):
            return cmd, note
    return None
