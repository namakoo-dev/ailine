def _d(y: int, m: int, d: int) -> dt.date:
    return dt.date(y, m, d)


def _cluster(vendor: str, tag: str, entries: list) -> list:
    """同一取引先の複数請求を「冊」のリストに展開する。

    entries: [(請求日 | None, 請求番号, 請求額), ...]
    ★ 請求日=None は「請求日ラベルはあるが値が空」の罠専用（mk_monthend.py 側で判定して書く）。
    """
    out = []
    for i, (date, invno, amount) in enumerate(entries, 1):
        fid = f"{tag}{i:02d}"
        out.append(dict(
            id=fid, 取引先=vendor, 請求日=date, 請求番号=invno, 請求額=amount,
            ファイル名=f"{vendor}_{fid}.xlsx",
        ))
    return out


def _names(books: list) -> list:
    return [b["ファイル名"] for b in books]


